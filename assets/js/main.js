  // 1. 일자별 탭 전환 (Day Tabs Switching)
  // --------------------------------------------------
  $('.tab-btn').on('click', function () {
    var targetDay = $(this).data('day');

    // 탭 활성화 클래스 처리
    $('.tab-btn').removeClass('active').attr('aria-selected', 'false');
    $(this).addClass('active').attr('aria-selected', 'true');

    // 일자별 섹션 표시 전환
    if (targetDay === 'all') {
      $('.day-section').stop(true, true).fadeIn(250);
    } else {
      $('.day-section').hide();
      $('#day-' + targetDay).stop(true, true).fadeIn(250);
    }

    // 카테고리 필터 초기화
    $('.filter-btn').removeClass('active');
    $('.filter-btn[data-filter="all"]').addClass('active');
    $('.timeline-item').show();
  });

