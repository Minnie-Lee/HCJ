  // 카드 클릭 시 모달 오픈
  $(document).on('click', '.btn-detail, .timeline-item', function (e) {
    // 앵커나 다른 버튼 클릭 이벤트 버블링 방지
    if ($(e.target).closest('a, button').length && !$(e.target).closest('.btn-detail').length) {
      return;
    }

    var spotId = $(this).data('spot-id') || $(this).closest('.timeline-item').data('spot-id');
    var data = spotDetails[spotId];

    if (!data) return;

    // 모달 데이터 채우기
    $('#modal-category').text(data.category);
    $('#modal-title-kr').text(data.titleKr);
    $('#modal-title-ja').text(data.titleJa);
    $('#modal-time').text(data.time);
    $('#modal-desc').text(data.desc);

    // 팁 리스트 렌더링
    var $tipsList = $('#modal-tips').empty();
    $.each(data.tips, function (index, tip) {
      $('<li></li>')
        .addClass('text-sm text-slate-700 bg-slate-50 p-2.5 rounded-lg border border-slate-200/80')
        .text(tip)
        .appendTo($tipsList);
    });

    // 모달 열기
    $('#detail-modal').addClass('is-open');
    $('body').css('overflow', 'hidden');
  });

  // 모달 닫기
  function closeModal() {
    $('#detail-modal').removeClass('is-open');
    $('body').css('overflow', '');
  }

  $('#modal-close-btn, .modal-backdrop-area').on('click', function () {
    closeModal();
  });

  // ESC 키 모달 닫기 (웹 접근성)
  $(document).on('keydown', function (e) {
    if (e.key === 'Escape' && $('#detail-modal').hasClass('is-open')) {
      closeModal();
    }
  });

  // --------------------------------------------------
  // 4. 스크롤 제어 & 탑 이동 (Scroll to Top)
  // --------------------------------------------------
  var $btnTop = $('#btn-top');

  $(window).on('scroll', function () {
    if ($(this).scrollTop() > 300) {
      $btnTop.addClass('is-visible');
    } else {
      $btnTop.removeClass('is-visible');
    }
  });

  $btnTop.on('click', function () {
    $('html, body').animate({ scrollTop: 0 }, 300);
  });

  // --------------------------------------------------
  // 5. 부드러운 앵커 이동
  // --------------------------------------------------
  $('a[href^="#"]').on('click', function (e) {
    var target = $(this.getAttribute('href'));
    if (target.length) {
      e.preventDefault();
      $('html, body').stop().animate({
        scrollTop: target.offset().top - 80
      }, 350);
    }
  });

